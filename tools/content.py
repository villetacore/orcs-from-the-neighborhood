def enrich(cards, add):
    by_id={c['id']:c for c in cards}
    for cid,(name,tag) in RENAMES.items():
        by_id[cid]['name']=name
        if tag: by_id[cid]['tag']=tag
    # Раздельные колоды устраняют цепочки событий и выдачу неприятностей за победу.
    by_id['raid']['text']='Возьми 1 Барахло и получи 1 крышак.'
    by_id['knight']['penalty']='coins'
    by_id['moth']['penalty']='coins'
    by_id['moth']['text']='Особых свойств нет.'
    by_id['tax']['text']='Заплати до 2 крышаков банку. Если денег не было — ничего не теряешь.'
    for cid,name,text,effect,flavor in HEROES:
        add(cid,name,'character',text,name,effect=effect,flavor=flavor)
    for cid,name,text,flavor in DISTRICTS:
        add(cid,name,'district',text,name,effect='none',flavor=flavor)
    for key,tier,name,text,image,flavor in PERKS:
        add('perk_'+key,name,'perk',text,'Shared motif: '+image,effect='none',tier=tier,
            image=f'assets/art/{image}.png',art_reuse=image,flavor=flavor)
    add('shop','Магазин Скупыча','shop','Две операции за ход: купить, продать за 1, обменять с доплатой, обновить за 1, разведать за 2. Три карты в витрине.','Goblin junk shop',effect='none',flavor='Мир кончился. Товарооборот — нет.')
    add('boss','Хозяин района','enemy','Финальное испытание с уровня 9. Сила: 14 + число твоих активных перков. Только эта победа даёт уровень 10.','Bureaucratic district landlord tyrant',strength=14,tag='spirit',level_reward=1,loot_cards=0,coins=0,effect='boss',penalty='level_coins',flavor='Аркадий Безадресный. Ключи от Южного узла, счёт за воздух.')
    for c in cards:
        c.setdefault('flavor',FLAVOR.get(c['id'],''))
        if c['type']=='enemy' and c['id']!='boss':
            c['level_reward']=1
            c['loot_cards']=2 if c['strength']>=7 else 1
            c['coins']=3 if c['strength']>=7 else 2
        if c['type']=='equipment': c['price']=6 if c['bonus']>=3 else (5 if c['bonus']==2 else 4)
        if c['type']=='consumable': c['price']=3 if c['effect'] in ('boost','energy','luck') else 2
        if c['type']=='chaos': c['price']=3
    return cards
