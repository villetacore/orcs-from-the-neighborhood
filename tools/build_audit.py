"""Рабочая таблица редакторского аудита → output/content-audit.md."""
import json, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools'))
from audit.decisions import D, T, PENDING, M
cards = json.loads((ROOT / 'data/cards.json').read_text())
missing = [c['id'] for c in cards if c['id'] not in D or c['id'] not in M]
extra = [k for k in {**D, **M} if k not in {c['id'] for c in cards}]
assert not missing and not extra, (missing, extra)
STEPS = {1:'1. Мелкие дела', 2:'2. Чужие условия', 3:'3. Право на адрес', 4:'4. Разборка'}
TYPES = {'character':'Герой','enemy':'Враг','equipment':'Снаряжение','consumable':'Расходник','event':'Событие','chaos':'Подстава','perk':'Перк','district':'Район','shop':'Магазин'}
rows = []
for c in cards:
    theme, role, name_q, flavor_q, art, decision, status = D[c['id']]
    place, link, step = M[c['id']]
    rows.append(f"| `{c['id']}` | {TYPES[c['type']]} | {c['name']} | {T[theme]} | {place} | {link} | {STEPS[step]} | {role} | {name_q} | {flavor_q} | {art} | {decision} | {status} |")
done = sum(1 for c in cards if D[c['id']][6].startswith('готово'))
factions = {}
for c in cards:
    for f in ('Управа','Союз дворов','Братство изоленты','Красная нежить','Дом Чёрного Бархата','Артель Глотка','Вольные ходоки','Лига трёх желаний'):
        if f in M[c['id']][1]: factions[f] = factions.get(f, 0) + 1
themes = {}
for c in cards: themes[T[D[c['id']][0]]] = themes.get(T[D[c['id']][0]], 0) + 1
build = (ROOT / 'tools/build_deck.py').read_text()
prefix = build.split("style='", 1)[1].split("'", 1)[0]
pending = '\n\n'.join(f"### `{k}` — {next(c['name'] for c in cards if c['id']==k)}\n\n```text\nUse case: stylized-concept. {prefix} Subject: {v}\n```" for k, v in PENDING.items())
text = f"""# Аудит контента

Производственный список этапа 1 из [плана](../docs/plan.md). Собирается `python3 tools/build_audit.py` из `tools/audit/decisions.py` и `data/cards.json`; правьте решения там, а не здесь.

Рассмотрено {len(cards)} из 90 ID. Готово: {done}. Ждут генерации изображений: {len(PENDING)}.

## Распределение тем

{chr(10).join(f'- {k}: {v}' for k, v in sorted(themes.items(), key=lambda x: -x[1]))}

Темы не должны быть равными: приключение, чудовища и торговля остаются каркасом, взрослые линии — заметными мотивами.

## Москва и фракции

Колонки «Москва», «Фракция / герой» и «Шаг истории» привязывают каждую карту к канону [game.md](../docs/game.md): Южный узел, восемь фракций и дуга «Последний свободный подъезд». Это редакторские метаданные; членство, репутация и поле в движке не реализованы. Карта может быть связана с несколькими фракциями или ни с одной.

{chr(10).join(f'- {k}: {v}' for k, v in sorted(factions.items(), key=lambda x: -x[1]))}

## Что изменено в этом проходе

- Текст врага теперь только его особое свойство; последствие поражения берётся из данных и печатается одинаково на экране и в SVG. Раньше 12 врагов дублировали последствие (и «сбрось карту» спорило с кодом: потеря случайная), а у Зомби-коммуниста вместо правила стояла реплика.
- Снаряжение без свойств больше не повторяет бонус из строки статов; Плащ уточнён: срабатывает при случайной потере.
- События и подставы, берущие карты, явно называют колоду Барахла; Проклятый лифт и Подстава у подъезда — «случайную карту», как в движке.
- Суккуба получила собственную карту в существующем слоте: «Курсы успеха от суккубы» (бывшая «Магия из ларька», эффект и цена прежние).
- Повторы ослаблены: шутки про БДСМ-клуб и доминирование убраны из реплик Дубины и Перфоратора, салон Эльвиры упоминается один раз, второй эльфийский запой заменён провалом памяти, мем «Нельзя просто…» убран из названия.
- Заголовки решений движка (Кикимора, оружие с ценой, вторая потеря) берут имя из карты; валидатор запрещает прежние имена переименованных карт в правилах и коде.
- Московская привязка: шесть районов получили названия из таблицы game.md (Чертановские топи, Мастерские Варшавского разлома, Ночной торг «Черкизон-2», Битцевская чаща, Калужский лабиринт, Курорт «Последний шанс»); Хозяин района назван Аркадием Безадресным в реплике; 18 реплик получили московские места и фракции (Битца, Варшавка, ВДНХ, Нижняя Москва, Башни обещаний, «Чёрный бархат», Управа). Подписи районов и перков в составе силы берутся из данных.

Механика, ID, категории, числа, теги и цены не менялись.

## Таблица

| ID | Категория | Название | Тема | Москва | Фракция / герой | Шаг истории | Роль | Название: оценка | Реплика | Картинка | Решение | Статус |
|---|---|---|---|---|---|---|---|---|---|---|---|---|
{chr(10).join(rows)}

## Очередь генерации

Встроенный генератор изображений в этой среде недоступен, поэтому ниже точные промпты. После генерации сохранить PNG в `assets/art/<id>.png`, добавить промпт и путь в `prompts/generated.json`, пересобрать данные и сменить статус в `tools/audit/decisions.py`. До этого карты используют прежние рисунки.

{pending}
"""
(ROOT / 'output/content-audit.md').write_text(text)
print(f'audit: {len(cards)} cards, {done} done, {len(PENDING)} pending images')
